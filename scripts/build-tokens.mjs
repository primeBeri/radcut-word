// Generates Fluent 2 design tokens as CSS custom properties (research R10, R11).
// Output is committed so the app builds without regenerating; `npm run build` refreshes it.
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { webDarkTheme, webLightTheme } from "@fluentui/tokens";

const out = join(import.meta.dirname, "..", "src", "ui", "theme", "tokens.css");

const shared = [];
const light = [];
const dark = [];
for (const [name, value] of Object.entries(webLightTheme)) {
  const darkValue = webDarkTheme[name];
  if (darkValue === value) shared.push([name, value]);
  else {
    light.push([name, value]);
    if (darkValue !== undefined) dark.push([name, darkValue]);
  }
}

const block = (selector, entries) =>
  `${selector} {\n${entries.map(([n, v]) => `  --${n}: ${v};`).join("\n")}\n}\n`;

const css =
  "/* Generated by scripts/build-tokens.mjs from @fluentui/tokens. Do not edit by hand. */\n\n" +
  block(":root", shared) +
  "\n" +
  block(':root,\n:root[data-theme="light"]', light) +
  "\n" +
  block(':root[data-theme="dark"]', dark);

writeFileSync(out, css);
console.log(`build-tokens: wrote ${shared.length + light.length} tokens to ${out}`);
